#!/usr/bin/env node
/**
 * Writes supabase/seed-coverage.sql from src/data/coverage.js: plain INSERTs for the coverage organisations, their login
 * users and their needs (D-070), for running in the Supabase SQL Editor. Idempotent (upserts on the fixed ids).
 * The same rows are what `npm run db:seed` would push; the SQL exists because seeding is sometimes not possible from here.
 *
 * Usage: node scripts/build-coverage-sql.mjs
 */
import { writeFileSync } from "node:fs";
import { COVERAGE_ORGANISATIONS, COVERAGE_USERS, COVERAGE_NEEDS } from "../src/data/coverage.js";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const orgs = COVERAGE_ORGANISATIONS.map(
  (o) => `  (${q(o.id)}, ${q(o.name.en)}, ${q(o.name.vi)}, ${q(o.mission.en)}, ${q(o.mission.vi)}, ${q(o.areaId)}, ${o.verified}, true, '{}')`,
).join(",\n");
const users = COVERAGE_USERS.map((u) => `  (${q(u.id)}, ${q(u.name)}, 'organisation', ${q(u.organisationId)})`).join(",\n");
const needs = COVERAGE_NEEDS.map(
  (n) =>
    `  (${q(n.id)}, ${q(n.organisationId)}, (select id from categories where lower(name) = lower(${q(n.category)})), ${q(n.priority ? "high" : "medium")}, ${n.quantity ?? "null"}, ${n.quantity === null ? "null" : "'items'"}, 'open', ${q(n.createdAt)})`,
).join(",\n");

const sql = `-- 3goods: coverage organisations (DECISIONS.md D-070). Run once in the Supabase SQL Editor.
-- ${COVERAGE_ORGANISATIONS.length} fictional organisations spread over provinces in proportion to the map's real community-facility distribution,
-- with their login users and needs. Idempotent (re-running updates the same rows). One transaction.
-- Requires supabase/migration-provinces.sql to have been run (province slugs, unit "items", one-need-per-category index).
-- Generated by scripts/build-coverage-sql.mjs from src/data/coverage.js: edit that, not this.

begin;

insert into organisations (id, name, name_vi, description, description_vi, city, verified, is_demo, past_received_item_ids) values
${orgs}
on conflict (id) do update set name = excluded.name, name_vi = excluded.name_vi, description = excluded.description,
  description_vi = excluded.description_vi, city = excluded.city, verified = excluded.verified, is_demo = excluded.is_demo;

insert into users (id, name, role, org_id) values
${users}
on conflict (id) do update set name = excluded.name, role = excluded.role, org_id = excluded.org_id;

insert into needs (id, org_id, category_id, priority, quantity, unit, status, created_at) values
${needs}
on conflict (id) do update set org_id = excluded.org_id, category_id = excluded.category_id, priority = excluded.priority,
  quantity = excluded.quantity, unit = excluded.unit, status = excluded.status;

commit;

-- Check afterwards: organisations per province (expect 31 in total, Hanoi 9 first)
--   select city, count(*) from organisations group by city order by count(*) desc;
`;
writeFileSync(new URL("../supabase/seed-coverage.sql", import.meta.url), sql);
console.log(`wrote supabase/seed-coverage.sql (${COVERAGE_ORGANISATIONS.length} organisations, ${COVERAGE_USERS.length} users, ${COVERAGE_NEEDS.length} needs)`);
